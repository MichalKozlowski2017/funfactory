/**
 * How big a coloring page must be on screen for a child's finger: for every page the smallest picture width (points)
 * at which its small parts are still about 14 pt across (7 pt inscribed radius; the 2 smallest parts may be smaller, the
 * smart touch finds them when touched precisely). Slivers (gaps between lines, radius < 4 px) are ignored.
 * The page is prepared exactly like in the game (crop to the outlines, 640 px, buildRegions).
 *   node games/bystrzakowo/scripts/coloring-sizes.ts [files.png...]     # print (candidates)
 *   node games/bystrzakowo/scripts/coloring-sizes.ts --write            # all pages -> src/sim/coloring-sizes.ts
 */
import { execFileSync } from 'node:child_process';
import { readdirSync, writeFileSync } from 'node:fs';
import { basename, join } from 'node:path';
import { buildRegions } from '../src/sim/fill.ts';

const SIZE = 640;
const MIN_RADIUS_PT = 7;
const game = join(import.meta.dirname, '..');
const dir = join(game, 'public/art/coloring-pages');
const write = process.argv.includes('--write');
const files = process.argv.slice(2).filter((a) => !a.startsWith('--'));
const list = files.length ? files : readdirSync(dir).filter((f) => f.endsWith('.png')).map((f) => join(dir, f));

const gray = (file: string, crop = '') =>
  execFileSync('ffmpeg', ['-v', 'error', '-i', file, '-filter_complex', `color=white:s=${SIZE}x${SIZE}[bg];[0]scale=${SIZE}:${SIZE}${crop}[f];[bg][f]overlay=format=auto,format=gray`, '-frames:v', '1', '-f', 'rawvideo', '-'], { maxBuffer: 1 << 24 });

export function pageMinWidth(file: string): { width: number; parts: number; radii: number[] } {
  let g = gray(file);
  // Crop to the outlines like the game (scenes/coloring.ts prepare).
  let x0 = SIZE, y0 = SIZE, x1 = -1, y1 = -1;
  for (let i = 0; i < SIZE * SIZE; i++)
    if (g[i]! < 150) {
      const x = i % SIZE, y = (i - x) / SIZE;
      x0 = Math.min(x0, x); x1 = Math.max(x1, x); y0 = Math.min(y0, y); y1 = Math.max(y1, y);
    }
  if (x1 >= 0) {
    const side = Math.min(SIZE, Math.round(Math.max(x1 - x0 + 1, y1 - y0 + 1) * 1.06));
    const sx = Math.round(Math.max(0, Math.min(SIZE - side, x0 + (x1 - x0 + 1) / 2 - side / 2)));
    const sy = Math.round(Math.max(0, Math.min(SIZE - side, y0 + (y1 - y0 + 1) / 2 - side / 2)));
    g = gray(file, `,crop=${side}:${side}:${sx}:${sy},scale=${SIZE}:${SIZE}`);
  }
  const r = buildRegions(SIZE, SIZE, (i) => g[i]! < 150);
  const radii = r.sizes
    .map((_, l) => l)
    .filter((l) => l && l !== r.background && !r.detail[l] && !r.keepWhite[l] && r.radius[l]! >= 4)
    .map((l) => r.radius[l]!)
    .sort((a, b) => a - b);
  const key = radii[Math.min(2, radii.length - 1)] ?? SIZE;
  return { width: Math.ceil((MIN_RADIUS_PT * SIZE) / key), parts: radii.length, radii: radii.slice(0, 6) };
}

const out: Record<string, number> = {};
for (const f of list.sort()) {
  const m = pageMinWidth(f);
  out[basename(f, '.png')] = m.width;
  if (!write) console.log(basename(f, '.png').padEnd(26), `min width ${String(m.width).padStart(4)} pt`, `parts ${String(m.parts).padStart(3)}`, `smallest ${m.radii.join(',')}`);
}
if (write) {
  const body = Object.entries(out).map(([k, v]) => `  '${k}': ${v},`).join('\n');
  writeFileSync(join(game, 'src/sim/coloring-sizes.ts'), `/** Generated by scripts/coloring-sizes.ts: the smallest picture width (points) at which a page's parts fit a child's finger. */\nexport const MIN_WIDTH: Record<string, number> = {\n${body}\n};\n`);
  console.log(`wrote ${Object.keys(out).length} pages`);
}
